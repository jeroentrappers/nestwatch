"""Writes a WiX (v4/v5 schema) source for the Nestwatch Windows installer.

    python packaging/windows/make-wxs.py VERSION STAGE_DIR OUT.wxs

STAGE_DIR holds nestwatch-desktop.exe, nestwatch-station.exe and web/ (the
browser listener bundle, found by the app as <exe dir>/web, OPEN-QUESTIONS
UI-10). Every file under it is installed to "C:\\Program Files\\Nestwatch".
Build the .msi with the WiX .NET tool:

    wix build -arch x64 -o nestwatch-windows-x86_64.msi OUT.wxs
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path
from xml.sax.saxutils import quoteattr

# Never change: Windows uses it to recognise upgrades of the same product.
UPGRADE_CODE = "E06F9B44-EB17-4745-99DA-46D9C58B7DD2"
ICON = Path(__file__).resolve().parent.parent / "icons" / "nestwatch.ico"


def ident(prefix: str, rel: str) -> str:
    return prefix + hashlib.sha1(rel.encode()).hexdigest()[:20]


def tree(dir_: Path, stage: Path, depth: int) -> list[str]:
    pad = "  " * depth
    out = []
    for p in sorted(dir_.iterdir()):
        rel = p.relative_to(stage).as_posix()
        if p.is_dir():
            out.append(f"{pad}<Directory Id={quoteattr(ident('d', rel))} Name={quoteattr(p.name)}>")
            out += tree(p, stage, depth + 1)
            out.append(f"{pad}</Directory>")
        else:
            cid, fid = ident("c", rel), ident("f", rel)
            if rel == "nestwatch-desktop.exe":
                fid = "MainExe"
            out.append(f"{pad}<Component Id={quoteattr(cid)}>")
            if fid == "MainExe":
                out.append(f"{pad}  <File Id={quoteattr(fid)} Source={quoteattr(str(p))} KeyPath=\"yes\">")
                out.append(
                    f'{pad}    <Shortcut Id="StartMenuShortcut" Directory="ProgramMenuFolder" Name="Nestwatch" '
                    f'Description="Private, local-first baby monitor" WorkingDirectory="INSTALLFOLDER" '
                    f'Icon="nestwatch.ico" Advertise="yes" />'
                )
                out.append(f"{pad}  </File>")
            else:
                out.append(f"{pad}  <File Id={quoteattr(fid)} Source={quoteattr(str(p))} KeyPath=\"yes\" />")
            out.append(f"{pad}</Component>")
    return out


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    version, stage, out = sys.argv[1], Path(sys.argv[2]).resolve(), Path(sys.argv[3])
    # MSI versions are numeric (major.minor.build): 0.2.0-rc.1 -> 0.2.0
    m = re.match(r"(\d+)\.(\d+)\.(\d+)", version)
    if not m:
        sys.exit(f"version {version!r} is not x.y.z")
    msi_version = ".".join(m.groups())
    for name in ("nestwatch-desktop.exe", "nestwatch-station.exe", "web/index.html"):
        if not (stage / name).is_file():
            sys.exit(f"missing {stage / name}")
    files = "\n".join(tree(stage, stage, 4))
    wxs = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packaging/windows/make-wxs.py; do not edit. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Package Name="Nestwatch" Manufacturer="Nestwatch" Version="{msi_version}"
           UpgradeCode="{UPGRADE_CODE}" Scope="perMachine" Language="1033">
    <SummaryInformation Description="Nestwatch {version}: private, local-first baby monitor" />
    <MajorUpgrade DowngradeErrorMessage="A newer version of Nestwatch is already installed." />
    <MediaTemplate EmbedCab="yes" CompressionLevel="high" />
    <Icon Id="nestwatch.ico" SourceFile={quoteattr(str(ICON))} />
    <Property Id="ARPPRODUCTICON" Value="nestwatch.ico" />
    <Property Id="ARPURLINFOABOUT" Value="https://nestwatch.appmire.be/" />
    <Property Id="ARPHELPLINK" Value="https://github.com/jeroentrappers/nestwatch/issues" />
    <StandardDirectory Id="ProgramMenuFolder" />
    <StandardDirectory Id="ProgramFiles64Folder">
      <Directory Id="INSTALLFOLDER" Name="Nestwatch">
{files}
      </Directory>
    </StandardDirectory>
    <Feature Id="Main" Title="Nestwatch">
      <ComponentGroupRef Id="AllFiles" />
    </Feature>
  </Package>
  <Fragment>
    <ComponentGroup Id="AllFiles" Directory="INSTALLFOLDER">
{chr(10).join(f'      <ComponentRef Id="{c}" />' for c in re.findall(r'<Component Id="([^"]+)"', files))}
    </ComponentGroup>
  </Fragment>
</Wix>
"""
    out.write_text(wxs, encoding="utf-8")
    print(f"wrote {out} (version {msi_version})")


if __name__ == "__main__":
    main()
